#!/usr/bin/env python3
"""Prepare a *local* signed WebReader update manifest; never publish or install.

Requires a separately provisioned ECDSA P-256 private key and matching public
key OUTSIDE this Git repository. Production keys are not generated by this
tool or CI. This tool NEVER uploads or executes an IPA.

Example, after independent QA and with trusted keys stored outside the repo:
 python3 ci/prepare_signed_webreader_update.py \
   --ipa /safe/release/WebReader-iOS12-unsigned.ipa \
   --private-key /secure/off-repo/release-private.pem \
   --public-key /secure/off-repo/release-public.pem \
   --notes-file /safe/release/notes.json \
   --published-at 2026-11-05T03:00:00Z \
   --output /safe/release/channel-development-v1.json
The matching IPA must *separately* be uploaded as a PUBLIC, immutable
GitHub Release asset at the URL included in the signed payload.
"""
import argparse
import base64
from datetime import datetime
import hashlib
import json
import os
from pathlib import Path
import plistlib
import subprocess
import tempfile
import zipfile

from validate_webreader_ipa import validate_ipa, IPARejected
from webreader_update_manifest import validate, ManifestRejected

REPO = Path(__file__).resolve().parent.parent.resolve()
APP = "Payload/MangaReader12.app/Info.plist"
MAX_NOTES = 20

class ReleasePreparationRejected(ValueError):
    pass

def ensure_external(path: Path, *, required: bool = True) -> Path:
    if required and (not path.is_file() or path.is_symlink()):
        raise ReleasePreparationRejected("missing or symlinked key/IPA/notes file")
    resolved = path.resolve()
    if resolved == REPO or REPO in resolved.parents:
        raise ReleasePreparationRejected("release inputs and secrets must be outside the repo")
    return resolved

def read_plist(ipa: Path) -> dict:
    try:
        with zipfile.ZipFile(ipa, "r") as z:
            info = plistlib.loads(z.read(APP))
        if not isinstance(info, dict):
            raise ReleasePreparationRejected("invalid app metadata")
        return info
    except (KeyError, OSError, ValueError, zipfile.BadZipFile) as exc:
        raise ReleasePreparationRejected("invalid IPA metadata") from exc

def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for data in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(data)
    return digest.hexdigest()

def prepare(
    ipa: Path, private_key: Path, public_key: Path, notes_file: Path,
    output: Path, published_at: str, installed_build: int = 56
) -> dict:
    ipa = ensure_external(ipa)
    private_key = ensure_external(private_key)
    public_key = ensure_external(public_key)
    notes_file = ensure_external(notes_file)
    output = ensure_external(output, required=False)
    if output.exists() or output.is_symlink():
        raise ReleasePreparationRejected("output already exists; refusing overwrite")
    if not output.parent.is_dir():
        raise ReleasePreparationRejected("output directory does not exist")
    if output == private_key or output == public_key or output == ipa:
        raise ReleasePreparationRejected("unsafe output destination")
    try:
        datetime.strptime(published_at, "%Y-%m-%dT%H:%M:%SZ")
        if len(published_at) != 20 or not published_at.endswith("Z"):
            raise ValueError("timestamp must be exact UTC RFC3339")
    except ValueError as exc:
        raise ReleasePreparationRejected("invalid UTC publication timestamp") from exc
    try:
        notes = json.loads(notes_file.read_text("utf-8"))
    except (UnicodeError, ValueError, OSError) as exc:
        raise ReleasePreparationRejected("notes must be a UTF-8 JSON array") from exc
    if not (isinstance(notes, list) and len(notes) <= MAX_NOTES and
            all(isinstance(x, str) and 1 <= len(x) <= 240 for x in notes)):
        raise ReleasePreparationRejected("notes must be <=20 nonempty strings, each <=240 chars")
    info = read_plist(ipa)
    build_string = info.get("CFBundleVersion")
    if not isinstance(build_string, str) or not build_string.isascii() or not build_string.isdecimal():
        raise ReleasePreparationRejected("invalid IPA build version")
    build = int(build_string)
    if build <= installed_build:
        raise ReleasePreparationRejected("IPA is not newer than installed build")
    digest = sha256_file(ipa)
    try:
        verified = validate_ipa(ipa, digest, installed_build, "12.5.8")
    except IPARejected as exc:
        raise ReleasePreparationRejected("IPA identity / ZIP / minimum iOS check rejected") from exc
    size = ipa.stat().st_size
    minimum = verified["minimumIOS"]
    payload = {
        "schemaVersion": 1,
        "application": "WebReader",
        "bundleId": "com.example.MangaReader12",
        "channel": "development",
        "build": build,
        "minimumIOS": minimum,
        "ipaUrl": ("https://github.com/AugustoArbulu/MangaReader12/"
                   f"releases/download/build{build}/WebReader-iOS12-unsigned.ipa"),
        "ipaSize": size,
        "sha256": digest,
        "releaseNotes": notes,
        "publishedAt": published_at,
    }
    payload_bytes = json.dumps(
        payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    if len(payload_bytes) > 32 * 1024:
        raise ReleasePreparationRejected("payload exceeds strict 32KiB limit")
    # Openssl signs only the payload bytes. Do not log, serialize or copy private key.
    with tempfile.TemporaryDirectory(prefix="webreader-sign-") as tmp:
        message = Path(tmp) / "payload"
        signature_path = Path(tmp) / "sig.der"
        message.write_bytes(payload_bytes)
        try:
            sign = subprocess.run(
                ["openssl", "dgst", "-sha256", "-sign", str(private_key),
                 "-out", str(signature_path), str(message)],
                check=False, capture_output=True, timeout=15,
            )
            if sign.returncode != 0:
                raise ReleasePreparationRejected("signing failed")
            signature = signature_path.read_bytes()
            # This also proves the supplied public/private pair actually matches.
            envelope = {
                "schemaVersion": 1, "algorithm": "ecdsa-p256-sha256",
                "payload": base64.b64encode(payload_bytes).decode("ascii"),
                "signature": base64.b64encode(signature).decode("ascii"),
            }
            encoded = json.dumps(
                envelope, sort_keys=True, separators=(",", ":")
            ).encode("utf-8") + b"\n"
            validate(encoded, public_key.read_bytes(), installed_build, "12.5.8")
        except (OSError, subprocess.TimeoutExpired, ManifestRejected) as exc:
            raise ReleasePreparationRejected("signature/key validation rejected") from exc
    if len(encoded) > 64 * 1024:
        raise ReleasePreparationRejected("envelope exceeds 64KiB")
    # Private staging output. Copy/publish only after independent authorization.
    fd = os.open(str(output), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(encoded)
            stream.flush()
            os.fsync(stream.fileno())
    except BaseException:
        output.unlink(missing_ok=True)
        raise
    return {
        "build": build, "signed_payload_sha256": hashlib.sha256(payload_bytes).hexdigest(),
        "ipa_sha256": digest, "ipa_size": size, "minimumIOS": minimum,
        "release_url": payload["ipaUrl"], "envelope_path": str(output),
        "published": False, "installation_performed": False,
    }

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ipa", type=Path, required=True)
    parser.add_argument("--private-key", type=Path, required=True)
    parser.add_argument("--public-key", type=Path, required=True)
    parser.add_argument("--notes-file", type=Path, required=True)
    parser.add_argument("--published-at", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--installed-build", type=int, default=56)
    args = parser.parse_args()
    result = prepare(
        args.ipa, args.private_key, args.public_key, args.notes_file,
        args.output, args.published_at, args.installed_build
    )
    print(json.dumps(result, indent=2, ensure_ascii=False))

if __name__ == "__main__":
    main()
